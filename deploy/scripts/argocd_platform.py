#!/usr/bin/env python3
"""Generate the Argo CD operator Applications (deploy/argocd/apps/<env>/platform.yaml) from
deploy/platform/operators.env, so k3d and the GitOps clusters install the same operator versions.

Usage: deploy/scripts/argocd_platform.py [--check]
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
REPO_URL = "https://github.com/Manuelma4/eu-disclosure-atlas.git"
ENVIRONMENTS = ("dev", "preview", "prod")
# Charts with large CRDs need server-side apply (client-side apply hits the annotation size limit).
SERVER_SIDE = {"strimzi", "kyverno", "keda", "cnpg", "external-secrets"}

TEMPLATE = """\
apiVersion: argoproj.io/v1alpha1
kind: Application
metadata:
  name: {env}-{release}
  namespace: argocd
  annotations:
    argocd.argoproj.io/sync-wave: "-2"
  finalizers: [resources-finalizer.argocd.argoproj.io]
spec:
  project: atlas-platform
  destination:
    server: https://kubernetes.default.svc
    namespace: {namespace}
  sources:
    - repoURL: {repo}
      chart: {chart}
      targetRevision: {version}
      helm:
        releaseName: {release}
        valueFiles: [$values/deploy/platform/values/{release}.yaml]
    - repoURL: {repo_url}
      targetRevision: main
      ref: values
  syncPolicy:
    automated: {{prune: true, selfHeal: true}}
    syncOptions: [CreateNamespace=true{server_side}]
"""


def operators() -> list[list[str]]:
    rows = []
    for line in (ROOT / "deploy/platform/operators.env").read_text().splitlines():
        if line.strip() and not line.startswith("#"):
            rows.append(line.split())
    return rows


def render(env: str) -> str:
    header = (
        "# Generated by deploy/scripts/argocd_platform.py from deploy/platform/operators.env; do not edit.\n"
        f"# Operators for the {env} cluster, synced before the platform manifests and the Atlas release.\n"
    )
    docs = [
        TEMPLATE.format(
            env=env, release=release, namespace=namespace, repo=repo, chart=chart, version=version,
            repo_url=REPO_URL, server_side=", ServerSideApply=true" if release in SERVER_SIDE else "",
        )
        for release, namespace, repo, chart, version in operators()
    ]
    return header + "---\n".join(docs)


def main() -> int:
    check = "--check" in sys.argv[1:]
    stale = []
    for env in ENVIRONMENTS:
        path = ROOT / f"deploy/argocd/apps/{env}/platform.yaml"
        text = render(env)
        if check:
            if not path.exists() or path.read_text() != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(text)
    if stale:
        print("out of date, run deploy/scripts/argocd_platform.py:", *stale, sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
